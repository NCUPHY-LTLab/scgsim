"""Generate bilingual API pages and a source-bound public reference index.

The generator reads Python syntax and authored Markdown only. It never imports
SCGSim or initializes a solver.
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any, TypeAlias

ROOT = Path(__file__).resolve().parents[1]
NAMESPACES = (
    "aedt",
    "aedt.specs",
    "geometry",
    "palace",
    "semantics",
    "visualization",
)
INDEX_PATH = "docs/reference/api-index.qmd"
DETAIL_PATH = "docs/reference/api/analyze-epr.qmd"
CHINESE_INDEX_PATH = "zh-TW/docs/reference/api-index.qmd"
CHINESE_DETAIL_PATH = "zh-TW/docs/reference/api/analyze-epr.qmd"
USAGE_PATHS = (
    "docs/reference/api/analyze-epr-usage.md",
    "zh-TW/docs/reference/api/analyze-epr-usage.md",
)
# The URLs each page had before it moved, relative to the page; Quarto writes a redirect at each.
INDEX_ALIAS = "../api/input-index.html"
DETAIL_ALIAS = "../../api/analyze_epr.html"
WORKFLOW_PATH = "src/scgsim/aedt/epr/workflow.py"
ResourcePath: TypeAlias = str
_NamespaceGroups: TypeAlias = dict[str, Any]
"""One package's entry of ``api_groups``: its task ``title``/``title_zh`` and its ``groups``."""

_GENERATED_NOTE = (
    "<!-- Generated by scripts/generate_knowledge_reference.py from the package declarations and "
    "docs/knowledge-sources.json; edit those and regenerate. -->\n\n"
)
_ENGLISH_INDEX = {
    "title": "API index",
    "description": "The public names of each SCGSim package, grouped by the task they serve, with the page that explains each group.",
    "intro": "Every name below is importable from the package it is listed under. Each group links to the page "
    "that explains it; the signatures and arguments are in the names' docstrings.\n\n",
    "exports_anchor": "declared-public-exports",
    "sources_anchor": "generation-sources",
    "unbundled_anchor": "public-documents-outside-the-offline-bundle",
    "sources_heading": "## Generation sources\n\n| Source | SHA-256 |\n|---|---|\n",
    "unbundled_heading": "## Public documents outside the offline bundle\n\n"
    "The README and English `docs/*.qmd` pages are bundled; the following public documents remain in the repository.\n\n",
}
_CHINESE_INDEX = {
    "title": "API 索引",
    "description": "SCGSim 各套件的公開名稱，依用途分組，並附上說明各組的頁面。",
    "intro": "下列每個名稱都可由它所列的套件匯入。每組附上說明它的頁面；簽章與參數見各名稱的 docstring。\n\n",
    "exports_anchor": "宣告的公開匯出",
    "sources_anchor": "產生來源",
    "unbundled_anchor": "未收錄於離線套件的公開文件",
    "sources_heading": "## 產生來源\n\n| 來源 | SHA-256 |\n|---|---|\n",
    "unbundled_heading": "## 未收錄於離線套件的公開文件\n\n"
    "README 與英文 `docs/*.qmd` 會收錄於離線 bundle；以下文件僅保留在儲存庫。\n\n",
}


@dataclass(frozen=True)
class _DetailPage:
    root: Path
    usage_path: str
    signature: str
    sources: list[str]
    index: str
    chinese: bool


def render(root: Path = ROOT) -> dict[ResourcePath, str]:
    """Read fixed API facades and authored inputs, then render four pages."""
    sources = _generation_sources(root)
    inventory = _public_documents(root)
    groups = _api_groups(root, _facade_exports(root))
    signature = _analyze_epr_signature(root)
    english_usage, chinese_usage = (_read_text(root, path) for path in USAGE_PATHS)

    english_index = _render_index(root, inventory, groups, sources, chinese=False)
    chinese_index = _render_index(root, inventory, groups, sources, chinese=True)
    english_detail = _render_detail(
        english_usage,
        _DetailPage(root, USAGE_PATHS[0], signature, sources, english_index, False),
    )
    chinese_detail = _render_detail(
        chinese_usage,
        _DetailPage(root, USAGE_PATHS[1], signature, sources, chinese_index, True),
    )
    return {
        INDEX_PATH: english_index,
        DETAIL_PATH: english_detail,
        CHINESE_INDEX_PATH: chinese_index,
        CHINESE_DETAIL_PATH: chinese_detail,
    }


def _generation_sources(root: Path) -> list[str]:
    sources = [
        "scripts/generate_knowledge_reference.py",
        "docs/knowledge-sources.json",
        WORKFLOW_PATH,
        *USAGE_PATHS,
        *(
            f"src/scgsim/{namespace.replace('.', '/')}/__init__.py"
            for namespace in NAMESPACES
        ),
    ]
    for source in sources:
        _read_bytes(root, source)
    return sources


def _public_documents(root: Path) -> list[str]:
    inventory = json.loads(_read_text(root, "docs/knowledge-sources.json"))
    documents = inventory["public_documents"]
    if not isinstance(documents, list) or any(
        not isinstance(path, str) for path in documents
    ):
        raise ValueError("public_documents must be a list of paths")
    if documents != sorted(set(documents)):
        raise ValueError("Public document inventory must be unique and sorted")
    for path in documents:
        _read_bytes(root, path)
    return documents


def _api_groups(
    root: Path, exports: dict[str, list[str]]
) -> dict[str, _NamespaceGroups]:
    """The task groups of ``docs/knowledge-sources.json``: each declared name in exactly one group of its package.

    A name a facade declares that no group lists, or a grouped name no facade declares, fails generation, so
    the index never drops or invents a name.
    """
    groups = json.loads(_read_text(root, "docs/knowledge-sources.json"))["api_groups"]
    if sorted(groups) != sorted(NAMESPACES):
        raise ValueError(
            f"api_groups must name exactly the packages {sorted(NAMESPACES)}"
        )
    for namespace, entry in groups.items():
        grouped = [name for group in entry["groups"] for name in group["names"]]
        if len(grouped) != len(set(grouped)):
            raise ValueError(f"api_groups lists a name twice: scgsim.{namespace}")
        if sorted(grouped) != exports[namespace]:
            missing = sorted(set(exports[namespace]) - set(grouped))
            extra = sorted(set(grouped) - set(exports[namespace]))
            raise ValueError(
                f"api_groups of scgsim.{namespace} must list its declared names: "
                f"missing {missing}, not declared {extra}"
            )
    return groups


def _facade_exports(root: Path) -> dict[str, list[str]]:
    exports = {
        namespace: _declared_exports(root, namespace) for namespace in NAMESPACES
    }
    return exports


def _declared_exports(root: Path, namespace: str) -> list[str]:
    """Read literal __all__ assignments without importing a package facade."""
    source = f"src/scgsim/{namespace.replace('.', '/')}/__init__.py"
    tree = ast.parse(_read_text(root, source), filename=source)
    names: list[str] = []
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == "__all__"
            for target in node.targets
        ):
            names = _literal_names(node.value, namespace)
        elif (
            isinstance(node, ast.AugAssign)
            and isinstance(node.target, ast.Name)
            and node.target.id == "__all__"
        ):
            names.extend(_literal_names(node.value, namespace))
    if not names:
        raise ValueError(f"Explicit string __all__ required: scgsim.{namespace}")
    if len(names) != len(set(names)):
        raise ValueError(f"Duplicate __all__ entries: scgsim.{namespace}")
    return sorted(names)


def _literal_names(node: ast.expr, namespace: str) -> list[str]:
    value = ast.literal_eval(node)
    if not isinstance(value, (list, tuple)) or any(
        not isinstance(name, str) for name in value
    ):
        raise ValueError(f"String-list __all__ required: scgsim.{namespace}")
    return list(value)


def _analyze_epr_signature(root: Path) -> str:
    tree = ast.parse(_read_text(root, WORKFLOW_PATH), filename=WORKFLOW_PATH)
    function = next(
        (
            node
            for node in tree.body
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
            and node.name == "analyze_epr"
        ),
        None,
    )
    if function is None:
        raise ValueError("Public analyze_epr function was not found")
    arguments = function.args
    if arguments.posonlyargs or arguments.args or arguments.vararg or arguments.kwarg:
        raise ValueError("Review formatter when analyze_epr is no longer keyword-only")
    if function.returns is None:
        raise ValueError("analyze_epr needs a declared return annotation")

    parameters = []
    for argument, default in zip(
        arguments.kwonlyargs, arguments.kw_defaults, strict=True
    ):
        parameter = ast.unparse(argument)
        if default is not None:
            parameter += f" = {ast.unparse(default)}"
        parameters.append(f"    {parameter},")
    return (
        "def analyze_epr(\n    *,\n"
        + "\n".join(parameters)
        + (f"\n) -> {ast.unparse(function.returns)}: ...")
    )


def _render_index(
    root: Path,
    documents: list[str],
    groups: dict[str, _NamespaceGroups],
    sources: list[str],
    *,
    chinese: bool,
) -> str:
    """The reader's index of public names by task, with the generation record hidden from the rendered page."""
    text = _CHINESE_INDEX if chinese else _ENGLISH_INDEX
    parts = [
        _header(
            text["title"],
            text["description"],
            "docs/api/input-index",
            "reference",
            INDEX_ALIAS,
        ),
        _GENERATED_NOTE,
        text["intro"],
        # The heading of the old flat list; links to it keep landing at the top of the groups.
        f"[]{{#{text['exports_anchor']}}}\n\n",
    ]
    # The packages appear in the order of api_groups, the order a reader meets them: plan, solvers, the rest.
    for namespace, entry in groups.items():
        parts.append(_render_namespace(namespace, entry, chinese=chinese))
    parts.append(_render_generation_record(root, documents, sources, text))
    return "".join(parts)


def _render_namespace(namespace: str, entry: _NamespaceGroups, *, chinese: bool) -> str:
    """One package: its task as the heading, then each group's gloss, its page and its names."""
    suffix = "_zh" if chinese else ""
    link = "說明" if chinese else "Reference"
    parts = [
        f"## {entry['title' + suffix]}{'：' if chinese else ': '}`scgsim.{namespace}` {{#scgsim.{namespace}}}\n\n"
    ]
    for group in entry["groups"]:
        parts.append(
            f"**{group['title' + suffix]}.** {group['gloss' + suffix]} "
            f"[{link}]({group['page']})\n\n"
            + ", ".join(f"`{name}`" for name in group["names"])
            + ".\n\n"
        )
    return "".join(parts)


def _render_generation_record(
    root: Path, documents: list[str], sources: list[str], text: dict[str, str]
) -> str:
    """The source hashes and the unbundled documents, kept in the packaged page but hidden when it is rendered."""
    unbundled = [
        path
        for path in documents
        if path != "README.md"
        and not (path.startswith("docs/") and path.endswith(".qmd"))
    ]
    parts = [
        # The two hidden headings had these anchors when they were shown; keep them on the page.
        f"[]{{#{text['sources_anchor']}}}[]{{#{text['unbundled_anchor']}}}\n\n",
        "::: {.content-hidden}\n\n",
        text["sources_heading"],
    ]
    parts.extend(f"| `{source}` | `{_digest(root, source)}` |\n" for source in sources)
    parts.append("\n" + text["unbundled_heading"])
    parts.extend(f"- `{path}`\n" for path in unbundled)
    parts.append("\n:::\n")
    return "".join(parts)


def _render_detail(usage: str, page: _DetailPage) -> str:
    title = (
        "analyze_epr：由已儲存的 HFSS 場重新計算 EPR"
        if page.chinese
        else "analyze_epr: compute EPR again from saved HFSS fields"
    )
    description = (
        "何時使用 analyze_epr、最小呼叫、它回傳什麼、參數與函式簽章。"
        if page.chinese
        else "When to use analyze_epr, a minimal call, what it returns, its parameters and its signature."
    )
    identifier = "docs/api/scgsim-aedt/analyze_epr"
    parts = [
        _header(title, description, identifier, "api", DETAIL_ALIAS),
        usage.rstrip(),
        "\n\n",
    ]
    # The signature restates the parameter table, so it is collapsed; its id keeps the old heading's anchor.
    parts.append(
        '::: {#函式簽章 .callout-note collapse="true" title="函式簽章"}\n\n```python\n'
        if page.chinese
        else '::: {#signature .callout-note collapse="true" title="Signature"}\n\n```python\n'
    )
    parts.extend((page.signature, "\n```\n\n:::\n\n"))
    label = "完整產生索引" if page.chinese else "Complete generation index"
    index_path = CHINESE_INDEX_PATH if page.chinese else INDEX_PATH
    index_hash = hashlib.sha256(page.index.encode("utf-8")).hexdigest()
    index_link = f"../{Path(index_path).name}"
    parts.append(
        f"其他公開名稱見 [API 索引]({index_link})。\n\n"
        if page.chinese
        else f"The other public names are in the [API index]({index_link}).\n\n"
    )
    # The hashes bind the page to its sources in the offline bundle; the rendered page leaves them out.
    parts.append("::: {.content-hidden}\n\n")
    parts.append(
        "## 直接來源\n\n| 來源 | SHA-256 |\n|---|---|\n"
        if page.chinese
        else "## Direct sources\n\n| Source | SHA-256 |\n|---|---|\n"
    )
    for source in (WORKFLOW_PATH, page.usage_path):
        if source not in page.sources:
            raise ValueError(
                f"Reference source is missing from source inventory: {source}"
            )
        parts.append(f"| `{source}` | `{_digest(page.root, source)}` |\n")
    parts.append(f"\n{label}, SHA-256 `{index_hash}`.\n\n:::\n")
    return "".join(parts)


def _header(
    title: str, description: str, identifier: str, kind: str, alias: str
) -> str:
    fields = (
        ("title", title),
        ("description", description),
        ("scgsim-id", identifier),
        ("scgsim-kind", kind),
        ("scgsim-status", "CONVERGING"),
    )
    values = "".join(
        f"{key}: {json.dumps(value, ensure_ascii=False)}\n" for key, value in fields
    )
    return f"---\n{values}aliases:\n  - {alias}\n---\n\n"


def _digest(root: Path, path: str) -> str:
    return hashlib.sha256(_read_bytes(root, path)).hexdigest()


def _read_text(root: Path, path: str) -> str:
    return _read_bytes(root, path).decode("utf-8")


def _read_bytes(root: Path, path: str) -> bytes:
    source = root / path
    if source.resolve() != source or not source.is_file():
        raise ValueError(f"Reference source must be a regular non-symlink file: {path}")
    return source.read_bytes()


def main() -> None:
    """Write generated pages, or report stale pages without changing them."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    for relative, content in render().items():
        destination = ROOT / relative
        if arguments.check:
            if (
                not destination.is_file()
                or destination.read_text(encoding="utf-8") != content
            ):
                raise SystemExit(f"Generated reference is stale: {relative}")
            continue
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
